"""Grounded chat assistant (US-30).

Retrieval is real and local (app/rag/store.py, no LLM needed for that — see
its module docstring). Only the final answer-synthesis step below calls
Claude, and only to compose a natural-language answer FROM the chunks we
already retrieved — it never gets to invent which sources exist.

Citations are never trusted as free text generated by the model. The
model is shown a numbered list of the chunks we actually retrieved and
asked which ones it used; we translate those indices back into citation
metadata ourselves. This makes "every citation maps to a real, retrievable
source chunk" (US-30 DoD) a structural guarantee rather than something we
hope the model gets right — an out-of-range or fabricated index is simply
dropped, never trusted.

Mirrors app/models.py's ExtractionStatus three-way split (US-10/US-12) with
an analogous AssistantStatus: ANSWERED / NOT_FOUND / AI_UNAVAILABLE.
NOT_FOUND is a *content* decision (the policy documents don't cover this,
or the question is out of scope, e.g. about the applicant's own
application) and AI_UNAVAILABLE is an *infrastructure* failure (no API key,
network error, or an unparseable response) — the same distinction that
matters for US-10 vs US-12 applies here for the same reason.
"""

import enum
import json
import logging
import re
from dataclasses import dataclass

from pydantic import BaseModel

from app.config import get_settings
from app.llm.client import run_text_completion
from app.llm.errors import AIUnavailableError
from app.llm.prompts import render_prompt
from app.rag.store import RetrievedChunk, retrieve_top_k

logger = logging.getLogger("onboardiq")

_CODE_FENCE_RE = re.compile(r"^```(?:json)?\s*(.*?)\s*```$", re.DOTALL)

_NOT_FOUND_MESSAGE = (
    "I don't have information about that in our policy documents. Please contact support for help with this "
    "question."
)
_UNAVAILABLE_MESSAGE = "I'm unable to answer questions right now — please try again shortly or contact support."


class AssistantStatus(str, enum.Enum):
    ANSWERED = "ANSWERED"
    NOT_FOUND = "NOT_FOUND"
    AI_UNAVAILABLE = "AI_UNAVAILABLE"


@dataclass(frozen=True)
class Citation:
    source_document: str
    section_reference: str


@dataclass(frozen=True)
class AssistantAnswer:
    status: AssistantStatus
    answer: str
    citations: list[Citation]
    retrieved_chunk_count: int


class _RagLLMResponse(BaseModel):
    relevant: bool
    answer: str
    used_chunk_indices: list[int] = []


def _strip_code_fence(text: str) -> str:
    match = _CODE_FENCE_RE.match(text.strip())
    return match.group(1) if match else text.strip()


def _build_context_block(chunks: list[RetrievedChunk]) -> str:
    return "\n\n".join(
        f"[{i + 1}] (Source: {chunk.source_document}, Section: {chunk.section_reference})\n{chunk.text}"
        for i, chunk in enumerate(chunks)
    )


def _resolve_citations(chunks: list[RetrievedChunk], used_indices: list[int]) -> list[Citation]:
    citations: list[Citation] = []
    seen: set[tuple[str, str]] = set()
    for index in used_indices:
        if not (1 <= index <= len(chunks)):
            continue  # out-of-range / hallucinated index — silently dropped, never trusted
        chunk = chunks[index - 1]
        key = (chunk.source_document, chunk.section_reference)
        if key not in seen:
            citations.append(Citation(source_document=chunk.source_document, section_reference=chunk.section_reference))
            seen.add(key)
    return citations


def answer_question(question: str) -> AssistantAnswer:
    settings = get_settings()

    # Real, local retrieval — no LLM involved (US-29).
    chunks = retrieve_top_k(question, settings.rag_top_k)
    logger.info(
        "RAG retrieval for question=%r returned %d chunk(s): %s",
        question,
        len(chunks),
        [c.chunk_id for c in chunks],
    )

    if not chunks:
        return AssistantAnswer(
            status=AssistantStatus.NOT_FOUND, answer=_NOT_FOUND_MESSAGE, citations=[], retrieved_chunk_count=0
        )

    prompt_text = render_prompt("policy_assistant", question=question, context=_build_context_block(chunks))

    try:
        raw_text = run_text_completion(prompt_text, max_tokens=512)
        payload = json.loads(_strip_code_fence(raw_text))
        parsed = _RagLLMResponse.model_validate(payload)
    except AIUnavailableError:
        return AssistantAnswer(
            status=AssistantStatus.AI_UNAVAILABLE,
            answer=_UNAVAILABLE_MESSAGE,
            citations=[],
            retrieved_chunk_count=len(chunks),
        )
    except Exception as exc:  # malformed/unparseable response — never crash the endpoint (US-09-style defensiveness)
        logger.exception("Policy assistant response could not be parsed for question=%r", question)
        return AssistantAnswer(
            status=AssistantStatus.AI_UNAVAILABLE,
            answer=_UNAVAILABLE_MESSAGE,
            citations=[],
            retrieved_chunk_count=len(chunks),
        )

    if not parsed.relevant:
        return AssistantAnswer(
            status=AssistantStatus.NOT_FOUND,
            answer=parsed.answer or _NOT_FOUND_MESSAGE,
            citations=[],
            retrieved_chunk_count=len(chunks),
        )

    return AssistantAnswer(
        status=AssistantStatus.ANSWERED,
        answer=parsed.answer,
        citations=_resolve_citations(chunks, parsed.used_chunk_indices),
        retrieved_chunk_count=len(chunks),
    )
